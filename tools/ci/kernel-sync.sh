#!/bin/bash
# Sync pkgs/linux-kriss with the latest CachyOS kernel patch release: regenerate the
# patch series, config, SOURCES.md and the version fields of the PKGBUILD.
# Does nothing when the PKGBUILD already tracks the latest upstream tag.
# Needs git, gh (authenticated), curl. Source only: nothing here downloads a binary.
#
# ponytail: only a new upstream tag triggers a sync. A config or BORE patch change
# without a new tag is picked up on the next tag; pass --force to resync now.
set -euo pipefail

pkg=$(cd "$(dirname "$0")/../../pkgs/linux-kriss" && pwd)
up=https://github.com/CachyOS
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# The upstream PKGBUILD names the release: kernel version, tag and matching config.
git clone -q --depth 1 "$up/linux-cachyos" "$work/pkgbuild"
pkgbuild_rev=$(git -C "$work/pkgbuild" rev-parse HEAD)
val() { sed -n "s/^$1=//p" "$work/pkgbuild/linux-cachyos/PKGBUILD" | head -n1; }
major=$(val _major)
ver=$major.$(val _minor)
tag=cachyos-$ver-$(val _tagrel)
kver=${ver%.0} # kernel.org calls 7.4.0 "7.4"

if grep -qx "_upstream_tag=$tag" "$pkg/PKGBUILD" && [ "${1:-}" != --force ]; then
  echo "linux-kriss already tracks $tag"
  exit 0
fi
echo "Syncing to $tag"

# Topic branches are rebased onto this series' release candidates, so history back to
# -rc1 is enough.
since=$(gh api "repos/torvalds/linux/commits/v$major-rc1" --jq .commit.committer.date)
git clone -q --bare --single-branch --branch "$tag" --shallow-since="$since" \
  "$up/linux" "$work/linux.git"
g() { git -C "$work/linux.git" "$@"; }
tip=$(g rev-parse "$tag^{commit}")
base=$(g log --first-parent --format='%H %s' "$tip" | awk -v s="Linux $kver" 'substr($0, 42) == s { print $1 }')
[ -n "$base" ] || { echo "no 'Linux $kver' commit under $tag" >&2; exit 1; }

rm -f "$pkg"/[0-9]*.patch
{
  cat <<HEAD
# linux-kriss sources

Generated by \`tools/ci/kernel-sync.sh\`; do not edit by hand.

The kernel is vanilla Linux $kver from kernel.org plus the patches below, all GPL-2.0.
They come from CachyOS's public source repositories and are built from source in our CI.
Patch contents are unmodified; each file keeps the upstream commit headers.

- Patch series: $up/linux tag \`$tag\` ($tip), on top of Linux $kver ($base).
  One patch per step on the tag's first-parent history, which is one per topic branch.
- \`config\`: $up/linux-cachyos \`linux-cachyos/config\` at $pkgbuild_rev.
  The PKGBUILD is derived from \`linux-cachyos/PKGBUILD\` in the same repository.
HEAD

  n=0
  for c in $(g rev-list --reverse --first-parent "$base..$tip"); do
    n=$((n + 1))
    subject=$(g log -1 --format=%s "$c")
    name=$(sed -E "s/^Merge branch '[^/']*\/([^']*)'.*/\1/; s/[^A-Za-z0-9.]+/-/g" <<<"$subject")
    file=$(printf '%04d-%s.patch' "$n" "$name")
    {
      echo "Origin: $up/linux tag $tag, commit $c ($subject)"
      echo "Squashed diff of the upstream commits below; their headers are unmodified."
      echo
      g log --no-merges --reverse --format='commit %H%nAuthor: %an <%ae>%nDate:   %ad%n%n%w(0,4,4)%B' "$c^1..$c"
      echo '---'
      g diff --binary "$c^1" "$c"
    } >"$pkg/$file"
    printf '\n## %s\n\n%s, commit %s\n\n' "$file" "$subject" "$c"
    g log --no-merges --reverse --format='    %h %s (%an)' "$c^1..$c"
  done

  # Kept byte for byte. BORE goes last, as upstream applies it.
  patches_rev=$(git ls-remote "$up/kernel-patches" HEAD | cut -f1)
  for path in misc/dkms-clang.patch sched/0001-bore-cachy.patch; do
    n=$((n + 1))
    name=${path##*/}
    name=${name#0001-}
    file=$(printf '%04d-%s' "$n" "$name")
    curl -fsSL "https://raw.githubusercontent.com/CachyOS/kernel-patches/$patches_rev/$major/$path" >"$pkg/$file"
    printf '\n## %s\n\n%s/kernel-patches %s/%s at %s\n\n    %s\n' "$file" "$up" "$major" "$path" \
      "$patches_rev" "$(sed -n 's/^From: //p' "$pkg/$file" | head -n1)"
  done
} >"$pkg/SOURCES.md"

cp "$work/pkgbuild/linux-cachyos/config" "$pkg/config"

sum=$(curl -fsSL "https://cdn.kernel.org/pub/linux/kernel/v${major%%.*}.x/sha256sums.asc" \
  | awk -v f="linux-$kver.tar.xz" '$2 == f { print $1 }')
[ -n "$sum" ] || { echo "no kernel.org checksum for linux-$kver.tar.xz" >&2; exit 1; }
sed -i.bak -E \
  -e "s/^pkgver=.*/pkgver=$ver/" \
  -e "s/^pkgrel=.*/pkgrel=1/" \
  -e "s/^_upstream_tag=.*/_upstream_tag=$tag/" \
  -e "s/^_tarball_sha256=.*/_tarball_sha256=$sum/" "$pkg/PKGBUILD"
rm "$pkg/PKGBUILD.bak"
